export interface I18nContextType {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: keyof (typeof translations)["en"]) => string;
}

export const I18nContext = createContext<I18nContextType | undefined>(undefined);

// Safe default for SSG/SSR pre-rendering when provider isn't mounted yet
const defaultI18n: I18nContextType = {
  locale: "en",
  setLocale: () => {},
  t: (key: keyof (typeof translations)["en"]) =>
    translations["en"][key as keyof (typeof translations)["en"]] || String(key),
};

export function useI18n(): I18nContextType {
  const context = useContext(I18nContext);
  // Return safe fallback during SSG/SSR instead of throwing
  if (!context) {
    return defaultI18n;
  }
  return context;
}

export function getTranslation(key: keyof (typeof translations)["en"], locale: Locale): string {
  return translations[locale][key as keyof (typeof translations)[Locale]] || key;
}
